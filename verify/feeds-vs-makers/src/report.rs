//! The readable report: summaries by material group, tool type, op class and maker, the outlier
//! clusters (ratio under 0.5 or over 1.5), the material classing and what was skipped.
use crate::{CLASSES, Row, Skips, held_out_by_maker, stats, summary};

fn fmt(s: Option<(f64, f64, f64, usize)>) -> String {
    match s {
        Some((m, lo, hi, n)) => format!("{m:.2} ({lo:.2}–{hi:.2}, n {n})"),
        None => "–".into(),
    }
}

fn table<F: Fn(&Row) -> String>(rows: &[Row], title: &str, key: F) -> String {
    let mut s = format!(
        "\n### By {title}\n\n| {title} | rpm ours/theirs | fz ours/theirs | feed rate ours/theirs |\n|---|---|---|---|\n"
    );
    for (k, a, b, c) in summary(rows, key) {
        s.push_str(&format!("| {k} | {} | {} | {} |\n", fmt(a), fmt(b), fmt(c)));
    }
    s
}

pub fn markdown(rows: &[Row], skips: &Skips) -> String {
    let mill: Vec<Row> = rows.iter().filter(|r| r.kind != "drill").cloned().collect();
    let drill: Vec<Row> = rows.iter().filter(|r| r.kind == "drill").cloned().collect();
    let mut s = String::from("# Our feeds and speeds against the tool makers' published numbers\n\n");
    s.push_str("Generated by `cargo run -p feeds-vs-makers` (verify/feeds-vs-makers). Ratios are ours / theirs; each cell is the median (10th–90th percentile, count). Ours: forge_tooling::resolve with the maker's own preset OFF (generic group table, material class, tool substrate), at the maker's own ae/ap, no machine clamps. Theirs: CAM-HAAS's cited raw rows (research/cam/tooling/raw/*.json; each row's URL is in rows.tsv). Ranges are taken at their middle.\n\n");
    s.push_str(&summary_for_david(&mill, &drill));
    s.push_str(&presets_on(rows));
    s.push_str("\n## Held out: each maker against a table derived from the OTHER makers only\n\nThe shipped speeds (and the N and P slot chips) are medians over all makers, so their match is by construction. Here each maker's rows are scored against the same derivation made without that maker (same group, same tool kind and substrate): the independent check. Rows whose group no other maker covers (K end mills: Lakeshore only; H: Helical only) cannot be held out and are left out.\n\n| held-out maker | rows | rpm ours/theirs | chip ours/theirs |\n|---|---|---|---|\n");
    for (m, n, a, b) in held_out_by_maker(rows) {
        s.push_str(&format!("| {m} | {n} | {} | {} |\n", fmt(a), fmt(b)));
    }
    s.push_str(&format!(
        "\n## Milling ({} rows)\n\nAll: rpm {}, fz {}, feed rate {}.\n",
        mill.len(),
        fmt(stats(mill.iter().map(|r| r.r_rpm()).collect())),
        fmt(stats(mill.iter().filter_map(|r| r.r_f()).collect())),
        fmt(stats(mill.iter().filter_map(|r| r.r_vf()).collect()))
    ));
    s.push_str(&table(&mill, "group", |r| r.group.to_string()));
    s.push_str(&table(&mill, "substrate", |r| r.substrate.to_string()));
    s.push_str(&table(&mill, "tool type", |r| r.kind.clone()));
    s.push_str(&table(&mill, "op class", |r| r.op.clone()));
    s.push_str(&table(&mill, "maker", |r| r.vendor.clone()));
    s.push_str(&table(&mill, "group × op class", |r| {
        format!("{} {}", r.group, r.op)
    }));
    s.push_str(&format!(
        "\n## Drilling ({} rows; `circular` rows are the very tables our defaults hold)\n",
        drill.len()
    ));
    s.push_str(&table(&drill, "group × substrate × independent", |r| {
        format!(
            "{} {} {}",
            r.group,
            r.substrate,
            if r.circular { "circular" } else { "independent" }
        )
    }));
    s.push_str(&table(&drill, "maker", |r| r.vendor.clone()));
    // outlier clusters
    s.push_str("\n## Outliers (a ratio under 0.5 or over 1.5), clustered by maker, group, op, tool type\n\n| cluster | rows | rpm median | fz median |\n|---|---|---|---|\n");
    let out: Vec<&Row> = rows
        .iter()
        .filter(|r| {
            let o = |x: f64| !(0.5..=1.5).contains(&x);
            o(r.r_rpm()) || r.r_f().is_some_and(o)
        })
        .collect();
    let mut keys: Vec<String> = out
        .iter()
        .map(|r| format!("{} {} {} {}", r.vendor, r.group, r.op, r.kind))
        .collect();
    keys.sort();
    keys.dedup();
    for k in keys {
        let sel: Vec<&&Row> = out
            .iter()
            .filter(|r| format!("{} {} {} {}", r.vendor, r.group, r.op, r.kind) == k)
            .collect();
        s.push_str(&format!(
            "| {k} | {} | {} | {} |\n",
            sel.len(),
            fmt(stats(sel.iter().map(|r| r.r_rpm()).collect())),
            fmt(stats(sel.iter().filter_map(|r| r.r_f()).collect()))
        ));
    }
    s.push_str("\n## How the makers' material texts were classed (first match wins)\n\n| keywords | ISO 513 group |\n|---|---|\n");
    for (k, g) in CLASSES {
        s.push_str(&format!(
            "| {} | {} |\n",
            k.join(", "),
            if g.is_empty() { "not compared" } else { g }
        ));
    }
    s.push_str("\n## Skipped\n\n");
    for (why, n) in &skips.0 {
        s.push_str(&format!("- {why}: {n}\n"));
    }
    s
}

/// The short readable summary: where we match the makers, where we are conservative or not.
fn summary_for_david(mill: &[Row], drill: &[Row]) -> String {
    let med = |v: Vec<f64>| stats(v).map_or(f64::NAN, |x| x.0);
    let by = |g: &str, f: &dyn Fn(&Row) -> Option<f64>| {
        med(mill.iter().filter(|r| r.group == g).filter_map(f).collect())
    };
    let mut s = String::from("## Summary\n\n");
    s.push_str("- What it found and fixed: our generic carbide speeds were forgeCAD placeholders 1.5–2.5× over every maker's median (P 180 against 66–104 m/min, K 160 against 64, M 110 against 67–76, H 60 against 37), and holding Guhring's high-performance drill series for every carbide drill ran drills 2–3× faster than YG-1's and Lakeshore's tables. Both are now the makers' pooled medians, cited.\n");
    {
        let ho = held_out_by_maker(&[mill, drill].concat());
        let line: Vec<String> = ho
            .iter()
            .filter(|x| x.1 > 0)
            .map(|(m, _, a, b)| {
                format!(
                    "{m} speed {:.2}{}",
                    a.map_or(f64::NAN, |x| x.0),
                    b.map_or(String::new(), |x| format!(", chip {:.2}", x.0))
                )
            })
            .collect();
        s.push_str(&format!(
            "- Held out (each maker against a table derived from the other makers only, the independent check): {}. The makers disagree with each other by up to ~2.5×: Harvey publishes bigger chips than the others (0.43 means the others' chips are 0.43 of Harvey's), Helical smaller chips and faster speeds, YG-1 slower drill speeds, Guhring's carbide drills run ~2.4× the others' speed. Our pooled table sits between them; no maker is more than 3× from the others (CI band).\n",
            line.join("; ")
        ));
    }
    s.push_str("- Read the speed medians below with that in mind: they are calibrated to these rows, so ~1.00 is by construction. The independent evidence is the chip by op class, the chips of the groups not calibrated (M, K, S, H) and the physics checks; the CI test's job is to stop any later change from skewing a row silently.\n");
    s.push_str(&format!(
        "- Over {} cited end-mill rows (Harvey, Helical, Lakeshore), our spindle speed is {:.2}× the makers' at the median and our feed per tooth {:.2}×.\n",
        mill.len(),
        med(mill.iter().map(|r| r.r_rpm()).collect()),
        med(mill.iter().filter_map(|r| r.r_f()).collect())
    ));
    s.push_str("- Per material group (median speed / chip, ours/theirs): ");
    let gs: Vec<String> = ["P", "M", "K", "N", "S", "H"]
        .iter()
        .map(|g| {
            format!(
                "{g} {:.2} / {:.2}",
                by(g, &|r| Some(r.r_rpm())),
                by(g, &|r| r.r_f())
            )
        })
        .collect();
    s.push_str(&gs.join(", "));
    s.push_str(". A chip under 1 is conservative. H's rows are Helical's two hardness classes (ratio 0.77 on one, 1.41 on the other, every tool type alike): one H speed sits between them; a hardness-aware H speed needs the part's hardness (forge-material's next keys).\n");
    let op = |o: &str| {
        med(mill
            .iter()
            .filter(|r| r.op == o)
            .filter_map(|r| r.r_f())
            .collect())
    };
    s.push_str(&format!(
        "- By op class (chip): slot {:.2}, rough {:.2}, finish {:.2}. Expected: makers allow a bigger chip roughing than slotting (we hold one chip per material), and their finishing chips are not raised for chip thinning while ours are (we hold the chip; they hold surface finish). Class-aware presets are next.\n",
        op("slot"),
        op("rough"),
        op("finish")
    ));
    let ind: Vec<&Row> = drill.iter().filter(|r| !r.circular).collect();
    s.push_str(&format!(
        "- Drills: {} rows; all but {} are rows our drill defaults were set from (a maker's own table or the pooled median), so they check drift, not independence.\n",
        drill.len(),
        ind.len()
    ));
    s.push_str("- The 10th–90th spread is wide because the makers disagree with each other (e.g. wrought aluminium: Harvey's series at 1000 SFM, Helical's H45AL at 2100); a tool's own maker data (its preset) is used ahead of these generic numbers whenever it exists.\n");
    s.push_str("- Model checks against makers' own published adjustments: radial chip thinning matches Helical's and Harvey's formula (forge-tooling feeds tests); ball-nose effective diameter matches CNCCookbook's worked example; the slot chip and drill feed rise with diameter as the makers' tables do (rows by diameter, interpolated).\n");
    s
}

fn on_table<F: Fn(&Row) -> String>(rows: &[&Row], title: &str, key: F) -> String {
    let mut s = format!("\n| {title} | rows | rpm ours/theirs | f ours/theirs |\n|---|---|---|---|\n");
    let mut keys: Vec<String> = rows.iter().map(|r| key(r)).collect();
    keys.sort();
    keys.dedup();
    for k in keys {
        let sel: Vec<&&Row> = rows.iter().filter(|r| key(r) == k).collect();
        s.push_str(&format!(
            "| {k} | {} | {} | {} |\n",
            sel.len(),
            fmt(stats(sel.iter().filter_map(|r| r.on_rpm()).collect())),
            fmt(stats(sel.iter().filter_map(|r| r.on_f()).collect()))
        ));
    }
    s
}

/// Presets ON: what an op actually gets by default when its tool carries the maker's presets.
fn presets_on(rows: &[Row]) -> String {
    let on: Vec<&Row> = rows.iter().filter(|r| r.on.is_some()).collect();
    let own: Vec<&Row> = rows.iter().filter(|r| r.own.is_some()).collect();
    let exact = own.iter().filter(|r| r.own_in_range() == Some(true)).count();
    let mut s = String::from("\n## Presets ON (the real default path)\n\n");
    s.push_str(&format!(
        "Each row run again as an op of the language runs it: the tool's own maker preset taken by `Tool::preset_for` for the op's class (the representative \"<group> <class>\", i.e. the maker's row for the group's representative material; a maker slot row is a slot, rough/max/finish rows run as rough because the language has no finishing class, the rest general), at the maker's ae/ap, no machine clamps. {} of {} rows have a preset for their group on their tool (the rest fall back to the generic table above).\n\n",
        on.len(),
        rows.len()
    ));
    s.push_str(&format!(
        "- All: rpm {}, f {}.\n",
        fmt(stats(on.iter().filter_map(|r| r.on_rpm()).collect())),
        fmt(stats(on.iter().filter_map(|r| r.on_f()).collect()))
    ));
    s.push_str(&format!(
        "- Reproduction: run with the preset written for that very row (its material text and engagement), {exact} of {} rows give a speed and feed inside the maker's printed range (ratio to the range's middle: rpm {}, f {}; the presets take a printed range at its low end, the maker's \"start here\", where this report takes the middle). This checks the inch conversion and that a preset's feed is read as the maker's programmed feed at its own width.\n",
        own.len(),
        fmt(stats(own.iter().filter_map(|r| r.own_rpm()).collect())),
        fmt(stats(own.iter().filter_map(|r| r.own_f()).collect()))
    ));
    s.push_str("- What the spread below means: the representative preset stands for every material of its group on that tool (e.g. Harvey's wrought-aluminium row runs a cast copper part too), so rows of other materials in the group differ by the maker's own material-to-material spread; and a maker's finish row runs on the rough preset re-thinned to the finishing width.\n");
    s.push_str(&on_table(&on, "group", |r| r.group.to_string()));
    s.push_str(&on_table(&on, "maker", |r| r.vendor.clone()));
    s.push_str(&on_table(&on, "maker op class", |r| r.op.clone()));
    s.push_str(&on_table(&on, "representative material?", |r| {
        let p = &r.on.as_ref().unwrap().preset;
        if r.own.is_some() && r.own_rpm() == r.on_rpm() && r.own_f() == r.on_f() {
            format!("same numbers as the row's own ({p})")
        } else {
            "another material or class".into()
        }
    }));
    s
}
