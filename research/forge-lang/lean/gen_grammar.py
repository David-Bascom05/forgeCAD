"""Regenerate ForgeLang/LL1/Forge.lean from the prototype's grammar.ll1.

Usage: python3 gen_grammar.py path/to/grammar.ll1 [NAME [examples]] > ForgeLang/LL1/NAME.lean
NAME (default Forge) is the module and namespace. An examples file holds lines
  accept NAME: TOK TOK ...   the derived parser reads these tokens (so a tree exists, parsesAll_tree)
  reject NAME: TOK TOK ...   the derived parser stops on them (fuel 400)
  nopredict NAME: NT TOK     no alternative of nonterminal NT is chosen on lookahead TOK
with terminals written as in the grammar ('(' ID NUM ...); `#` starts a comment.
The FIRST/FOLLOW tables it writes are a certificate only: the Lean kernel re-checks them
(`check`, by `decide +kernel`), so nothing computed here is trusted.
"""
import sys

THEOREMS = """set_option maxRecDepth 100000 in
/-- The check, run by the Lean kernel (no compiler trusted): the Forge grammar is LL(1). -/
theorem grammar_ll1 : check grammar certT = true := by decide +kernel

/-- So it is unambiguous: two parse trees of a program with the same tokens are the same tree. -/
theorem forge_unambiguous {t1 t2 : Tree} (h1 : VT grammar t1 (.n grammar.start))
    (h2 : VT grammar t2 (.n grammar.start)) (he : t1.yield = t2.yield) : t1 = t2 :=
  unambiguous grammar_ll1 h1 h2 he

/-- Its LL(1) parser gives every program's tree back from the tree's tokens. -/
theorem forge_roundtrip {t : Tree} (h : VT grammar t (.n grammar.start)) :
    parse grammar certT t.size (.n grammar.start) t.yield = some (t, []) :=
  roundtrip grammar_ll1 h

/-- What the parser returns for a whole input is a tree of exactly that input. -/
theorem forge_lossless {n : Nat} {w : List Tok} {t : Tree}
    (h : parse grammar certT n (.n grammar.start) w = some (t, [])) :
    VT grammar t (.n grammar.start) ∧ t.yield = w :=
  lossless h

/-- The check is not vacuous: infix minus with no precedence (`e := e '-' e | NUM`) fails it. -/
def ambiguous : Grammar := { start := 0, rules := [(0, [.n 0, .t 1, .n 0]), (0, [.t 0])] }
theorem ambiguous_rejected : check ambiguous = false := by decide +kernel

end ForgeLang.LL1.NAME"""

text = open(sys.argv[1]).read()
NAME = sys.argv[2] if len(sys.argv) > 2 else "Forge"
EXAMPLES = open(sys.argv[3]).read() if len(sys.argv) > 3 else ""
toks = "\n".join(l.split('#')[0] for l in text.splitlines()).split()
raw, cur = [], []
for t in toks:
    if t == ';':
        if cur:
            raw.append(cur)
            cur = []
    else:
        cur.append(t)
nts, defs = [], []
for r in raw:
    assert r[1] == ':=', r
    nts.append(r[0])
    alts, a = [], []
    for s in r[2:]:
        if s == '|':
            alts.append(a)
            a = []
        else:
            a.append(s)
    alts.append(a)
    defs.append((r[0], [[x for x in a if x != '%empty'] for a in alts]))

def terminal(s):
    return s.startswith("'") or s.isupper()

terms = []
for _, alts in defs:
    for a in alts:
        for s in a:
            if terminal(s):
                if s not in terms:
                    terms.append(s)
            else:
                assert s in nts, s + " is used but not defined"
ni = {n: i for i, n in enumerate(nts)}
ti = {t: i for i, t in enumerate(terms)}
rules = [(ni[n], [('t', ti[s]) if terminal(s) else ('n', ni[s]) for s in a], n, a) for n, alts in defs for a in alts]

nul, fst, fol = set(), {A: set() for A in range(len(nts))}, {A: set() for A in range(len(nts))}
def first_seq(seq):
    out = set()
    for k, x in seq:
        if k == 't':
            out.add(x)
            return out, False
        out |= fst[x]
        if x not in nul:
            return out, False
    return out, True
fol[0].add(None)
changed = True
while changed:
    changed = False
    for A, seq, _, _ in rules:
        f, n = first_seq(seq)
        if n and A not in nul:
            nul.add(A); changed = True
        if not f <= fst[A]:
            fst[A] |= f; changed = True
        for i, (k, B) in enumerate(seq):
            if k != 'n':
                continue
            f2, n2 = first_seq(seq[i + 1:])
            add = set(f2) | (fol[A] if n2 else set())
            if not add <= fol[B]:
                fol[B] |= add; changed = True

def lst(xs):
    return "[" + ", ".join(str(x) for x in sorted(xs)) + "]"
def olst(xs):
    return "[" + ", ".join("none" if x is None else f"some {x}" for x in sorted(xs, key=lambda o: -1 if o is None else o)) + "]"

o = ["import ForgeLang.LL1.Proof", "",
     "/-! Generated by `gen_grammar.py` from the prototype's `grammar.ll1`; regenerate on any syntax",
     "change, then `lake build` re-runs the kernel check. -/", "",
     f"namespace ForgeLang.LL1.{NAME}", "",
     "def ntNames : List String := [" + ", ".join(f'"{n}"' for n in nts) + "]",
     "def tNames : List String := [" + ", ".join('"' + t.replace('"', '\\"') + '"' for t in terms) + "]", "",
     "def grammar : Grammar where", "  start := 0", "  rules := ["]
for i, (A, seq, n, a) in enumerate(rules):
    syms = ", ".join(f".{k} {x}" for k, x in seq)
    o.append(f"    ({A}, [{syms}])" + ("," if i < len(rules) - 1 else "") + f"  -- {n} := {' '.join(a) or '%empty'}")
o.append("  ]")
o.append("")
o.append("/-- Certificate tables (untrusted; `check` verifies them). -/")
o.append("def certT : Tables :=")
o.append(f"  ⟨{lst(nul)},")
o.append("   tblOf [" + ", ".join(f"({A}, {lst(fst[A])})" for A in range(len(nts))) + "],")
o.append("   tblOf [" + ", ".join(f"({A}, {olst(fol[A])})" for A in range(len(nts))) + "]⟩")
o.append("")
# The theorems: without them `lake build` checks nothing, so they are written with the tables.
body = THEOREMS.replace("ForgeLang.LL1.NAME", f"ForgeLang.LL1.{NAME}")
ex = []
for line in EXAMPLES.splitlines():
    line = line.split('#')[0].strip()
    if not line:
        continue
    kind, rest = line.split(None, 1)
    name, toks = rest.split(':', 1)
    name, toks = name.strip(), toks.split()
    if kind == 'nopredict':
        A, a = toks
        ex.append(f"/-- No alternative of `{A}` is chosen on `{a}`. -/")
        ex.append(f"theorem nopredict_{name} : choose grammar certT {ni[A]} (some {ti[a]}) = none := by decide +kernel")
        continue
    ids = ", ".join(str(ti[t]) for t in toks)
    want = "true" if kind == 'accept' else "false"
    ex.append(f"/-- `{' '.join(toks)}` -/")
    ex.append(f"theorem {kind}_{name} : parsesAll grammar certT 400 [{ids}] = {want} := by decide +kernel")
if ex:
    i = body.index("end ForgeLang.LL1.")
    body = body[:i] + "\n".join(ex) + "\n\n" + body[i:]
o.append(body)
print("\n".join(o))
