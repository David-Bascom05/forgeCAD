#!/usr/bin/env python3
"""Generates kernel/forge-machine/data/machines/fadal.toml and parts/fadal/<machine>/ from the
spec tables on fadal.com's model pages (first party; restated in
research/cam/machines/fadal/fadal-com-2026-11-23.json, read 2026-11-23). These are the current
Fadal (revived brand) models, not the pre-2010 classics. Same rules as tools/machines/haas.py.

    python3 tools/machines/fadal.py
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import haas as H  # noqa: E402

ROOT = H.ROOT
FACTS = os.path.join(ROOT, "research/cam/machines/fadal/fadal-com-2026-11-23.json")
OUT = os.path.join(ROOT, "kernel/forge-machine/data/machines/fadal.toml")
PARTS = os.path.join(ROOT, "kernel/forge-machine/parts/fadal")
TAKEN = "2026-11-23"
IN = 25.4
# the VMC 4022 page lists travels and table only (no taper, tools or rates): not modelled
MODELS = ["vmc-2015h-s-ii", "vmc-2520", "vmc-3320", "vmc-4020b-ii", "vmc-6032", "vmc-6032-50t", "vmc-8032", "vmc-8032-50t"]


def first(s):
    """The standard value: the first of 'a/b*/c*' (the starred ones are options)."""
    return re.split(r"\s*/\s*", s.replace("”", ""))[0].strip()


def num(s):
    return float(first(s).replace(",", ""))


def main():
    facts = json.load(open(FACTS))
    text = ["# Fadal machines: forgecad's records from fadal.com's model pages, restated (never copied).",
            "# GENERATED by tools/machines/fadal.py; every value carries a [[machine.cite]]. Current Fadal models,",
            "# not the pre-2010 classics.", ""]
    for key in MODELS:
        f = facts[key]
        url = f"https://fadal.com/{key}/"
        name = "fadal-" + key
        r = H.Rec(name, {"url": url, "specs": {}})
        g = lambda k: f[k]  # noqa: E731
        tx, ty, tz = num(g("X-axis Travel (in.)")) * IN, num(g("Y-axis Travel (in.)")) * IN, num(g("Z-axis Travel (in.)")) * IN
        nmin, nmax = [float(x) * IN for x in first(g("Spindle Nose to Table (in.)")).split("-")]
        tl, tw = [float(x) * IN for x in re.split(r"\s*[x×]\s*", g("Table Dimensions (in.)"))]
        col = num(g("Spindle Center to Column (in.)")) * IN
        top = num(g("Spindle Speed (RPM)"))
        taper = first(g("Spindle Type")).replace("-", "")
        rates = g("Rapid Traverse Rate X,Y & Z (IPM)") if "Rapid Traverse Rate X,Y & Z (IPM)" in f else None
        ax, ay = tx / 2, ty / 2
        H.table(r, "machine", name=name, kind="vmc3", control="fanuc", real=True, length_joint="Z", coolants=[], clearance=1.0,
                source=url, taken=TAKEN,
                note=("forgecad's Fadal record from fadal.com's spec table; every value cited. Base frame = table top centre at "
                      "home; +x right, +y toward the column, +z up. Starred values on the page are options: the standard is used."))
        r.cite("machine.control", "unknown", basis="the control is not named on fadal.com's pages; the fanuc dialect stands in")
        r.cite("machine.kinematics", "estimate", basis="table X on saddle Y, head Z on the column (box-way VMC; not stated on the page)")
        if rates:
            rr = [float(x.replace(",", "")) * IN for x in re.split(r"\s*/\s*", rates)]
        for i, (n, parent, axis, t, k) in enumerate((("Y", "base", [0, -1, 0], ty, "Y-axis Travel (in.)"),
                                                      ("X", "Y", [-1, 0, 0], tx, "X-axis Travel (in.)"),
                                                      ("Z", "base", [0, 0, 1], tz, "Z-axis Travel (in.)"))):
            rate = rr[{"X": 0, "Y": 1, "Z": 2}[n]] if rates else 10000.0
            H.table(r, "machine.joint", name=n, parent=parent, side="head" if n == "Z" else "table", type="linear", axis=axis,
                    range=[round(-t, 2), 0], home=0, rapid=round(rate, 1), max_feed=round(rate, 1))
            r.cite(f"joint.{n}.range", "published", source=url, value=f"{k}: {g(k)}",
                   note="the standard travel (starred = option); machine zero at the + end is a stand-in")
            if rates:
                r.cite(f"joint.{n}.rapid", "published", source=url, value=f"Rapid Traverse Rate X,Y & Z (IPM): {rates}")
                r.cite(f"joint.{n}.max_feed", "unknown", basis="no cutting feed limit published; taken equal to the rapid (errs permissive)")
                if key == "vmc-4020b-ii":
                    r.cite(f"joint.{n}.rapid", "conflict", source=url, value="page text: 'rapid rates up to 900 IPM'",
                           note="the spec table says 1,000 IPM, the description 900 IPM; the record holds the table's 1,000 (shorter time estimates: t_min stays a lower bound)")
            else:
                r.cite(f"joint.{n}.rapid", "unknown", basis="no rapid rate on this model's page; 10 m/min stands in (time estimates only)")
                r.cite(f"joint.{n}.max_feed", "unknown", basis="as the rapid")
        nose = [ax, ay, nmax]
        tlen = num(g("Max. Tool Length (in.)")) * IN
        dkey = "Max. Tool Diameter (in.) (with adjacent tool)"
        dadj = float(re.search(r"\(([\d.]+)\)", g(dkey)).group(1)) * IN
        H.table(r, "machine.spindle", name="S1", link="Z", kind="milling", axis=[0, 0, 1], nose=nose, rpm=[1, top],
                max=[round(tlen, 1), round(dadj, 1)], interface=taper)
        r.cite("spindle.S1.rpm", "published", source=url, value=f"Spindle Speed (RPM): {g('Spindle Speed (RPM)')}", note=H.MIN_RPM)
        r.cite("spindle.S1.nose", "published", source=url, value=f"Spindle Nose to Table (in.): {g('Spindle Nose to Table (in.)')}",
               note="the standard Z; x, y: " + H.CENTRED)
        r.cite("spindle.S1.max", "published", source=url, value=f"Max. Tool Length (in.): {g('Max. Tool Length (in.)')}; {dkey}: {g(dkey)}",
               note="the diameter with adjacent tools (the smaller) is held")
        r.cite("spindle.S1.interface", "published", source=url, value=f"Spindle Type: {g('Spindle Type')}")
        r.cite("machine.power", "published", source=url,
               value=f"Spindle Torque (ft. lbs.): {g('Spindle Torque (ft. lbs.)')}; Spindle Motor (HP) Peak: {g('Spindle Motor (HP) Peak')}",
               note="peak power and torque without the rpm they hold at: no power curve declared")
        H.table(r, "machine.changer", pockets=int(num(g("Tool Capacity"))), change_s=3.0,
                max_tool_kg=round(num(g("Max. Tool Weight (lbs.)")) * 0.45359237, 2))
        r.cite("changer.pockets", "published", source=url, value=f"Tool Capacity: {g('Tool Capacity')}; {g('Tool Change Type')}")
        r.cite("changer.change_s", "unknown", basis="tool change time not on the page; 3 s stands in (time estimates only)")
        r.cite("changer.max_tool_kg", "published", source=url, value=f"Max. Tool Weight (lbs.): {g('Max. Tool Weight (lbs.)')}")
        H.table(r, "machine.mount", name="spindle", kind="tool", link="Z", at=nose, dir=[0, 0, -1])
        r.cite("mount.spindle.at", "published", source=url, value=f"Spindle Nose to Table (in.): {g('Spindle Nose to Table (in.)')}",
               note="gauge point at the nose face; x, y: " + H.CENTRED)
        H.table(r, "machine.mount", name="table", kind="part", link="X", at=[0, 0, 0], dir=[0, 0, 1], xdir=[1, 0, 0])
        r.cite("mount.table.at", "estimate", basis="the table top centre is the frame origin")
        th = 100.0
        lo, hi = [-tl / 2, -tw / 2, -th], [tl / 2, tw / 2, 0.0]
        H.body(r, "table", "X", [("box", lo, hi)],
               H.fg_box(f"{name} table: {g('Table Dimensions (in.)')} in published, thickness estimated", *H.shrink_box(lo, hi),
                        cut=(0, 0, tl, 18, 14)),
               status="published", source=url, value=f"Table Dimensions (in.): {g('Table Dimensions (in.)')}")
        r.cite("body.table", "estimate", basis=f"thickness {th:g} mm unpublished")
        nr, nh = 95.0 if "50" not in taper else 130.0, 160.0
        hw = 190.0 if "50" not in taper else 240.0
        hb_lo, hb_hi = [ax - hw, ay - hw, nmax + nh], [ax + hw, ay + col - 5, nmax + nh + 420]
        H.body(r, "head", "Z", [("cyl", [ax, ay, nmax], [0, 0, 1], nr, nh), ("box", hb_lo, hb_hi)],
               H.fg_head(f"{name} head: nose and housing back to the column (sizes unpublished)", ax, ay, nmax + 1, nr - 1, nh - 1,
                         [hb_lo[0] + 1, hb_lo[1] + 1, hb_lo[2]], [hb_hi[0] - 1, hb_hi[1] - 1, hb_hi[2] - 1]),
               ignore=["column"], status="unknown",
               basis=f"head size unpublished: nose r {nr:g} x {nh:g} mm, housing {2 * hw:g} mm wide back to the column (errs large)")
        cy = ay + col
        # from 5 mm above the table top: below it the column's face position is unknown (with the travel
        # taken centred, the table at full Y would reach into a full-height column, which the real
        # machine does not), so the body models the face that parts and fixtures could hit
        clo, chi = [-450, cy, 5.0], [450, cy + 400, nmax + nh + 800]
        H.body(r, "column", "base", [("box", clo, chi)],
               H.fg_box(f"{name} column: face at the published spindle-centre distance; size unpublished", *H.shrink_box(clo, chi)),
               ignore=["head"], status="published", source=url, value=f"Spindle Center to Column (in.): {g('Spindle Center to Column (in.)')}")
        r.cite("body.column", "estimate", basis="the face position is published (with the travel taken centred); 900 wide x 400 deep are stand-ins; the part of the column below the table top is not modelled")
        text.append("# " + "-" * 93)
        text += r.lines
        os.makedirs(os.path.join(PARTS, name), exist_ok=True)
        for (bname, link, prims, ignore, part) in r.bodies:
            text += [s.replace("parts/haas/", "parts/fadal/") for s in H.prim_toml(r, bname, link, prims, ignore, part)]
            with open(os.path.join(PARTS, name, f"{bname}.fg"), "w") as fh:
                fh.write(part)
        for c in r.cites:
            text.append("[[machine.cite]]")
            for k in ("path", "status", "source", "taken", "value", "basis", "note"):
                if c.get(k):
                    text.append(f"{k} = {H.tv(c[k])}")
        text.append("")
    with open(OUT, "w") as fh:
        fh.write("\n".join(text))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
