"""Offline derivations for forge-geom/src/meet.rs; writes forge-geom/src/meet_gen.rs.

Run: python3 tools/sympy/meet.py (needs sympy; nothing here runs at build time).

At each u of the host surface, the other parameter s is a root of F(u, s); the
curve turns back where two roots meet, so where the discriminant of F(u, .) in s
vanishes. Generated here:

- the discriminant of a quartic c0 + c1 s + ... + c4 s^4;
- the half-angle form of A0 + A1 cos t + B1 sin t + A2 cos 2t + B2 sin 2t, a quartic
  in w = tan(t/2) (the product with (1 + w^2)^2);
- the torus implicit along a line, a quartic in the line parameter.

The Rust is plain products and sums in a fixed order (no powi, no fused
multiply-add), so it evaluates the same everywhere. The script also checks the
degenerate cases meet.rs relies on.
"""

import os
import sympy as sp

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "kernel", "forge-geom", "src", "meet_gen.rs")


def rust(e, syms):
    """A polynomial in `syms` as Rust: each term a float times repeated products."""
    terms = sp.Poly(sp.expand(e), *syms).terms()
    out = []
    for powers, coeff in terms:
        coeff = sp.Rational(coeff)
        assert coeff.q == 1, coeff
        factors = [str(x) for x, k in zip(syms, powers) for _ in range(k)]
        mag = abs(int(coeff.p))
        body = " * ".join(([f"{mag}.0"] if mag != 1 or not factors else []) + factors)
        sign = "-" if coeff < 0 else "+"
        out.append((sign, body))
    if not out:
        return "0.0"
    first = ("-" if out[0][0] == "-" else "") + out[0][1]
    return first + "".join(f" {s} {b}" for s, b in out[1:])


def quartic_disc():
    c = sp.symbols("c0:5")
    s = sp.symbols("s")
    return sp.discriminant(sum(c[i] * s**i for i in range(5)), s), c


def trig2_to_w():
    a0, a1, b1, a2, b2, w = sp.symbols("a0 a1 b1 a2 b2 w")
    c = (1 - w**2) / (1 + w**2)
    s = 2 * w / (1 + w**2)
    f = a0 + a1 * c + b1 * s + a2 * (c**2 - s**2) + b2 * (2 * s * c)
    q = sp.expand(sp.cancel(f * (1 + w**2) ** 2))
    return [q.coeff(w, k) for k in range(5)], (a0, a1, b1, a2, b2)


def torus_on_line():
    # (|q|^2 + R^2 - r^2)^2 - 4 R^2 (qx^2 + qy^2) with q = p + v d, in terms of
    # |q|^2 + R^2 - r^2 = a2 v^2 + a1 v + a0 and qx^2 + qy^2 = b2 v^2 + b1 v + b0
    v, rr = sp.symbols("v rr")  # rr = 4 R^2
    a0, a1, a2, b0, b1, b2 = sp.symbols("a0 a1 a2 b0 b1 b2")
    f = sp.expand((a2 * v**2 + a1 * v + a0) ** 2 - rr * (b2 * v**2 + b1 * v + b0))
    return [f.coeff(v, k) for k in range(5)], (a0, a1, a2, b0, b1, b2, rr)


def checks():
    # Two cylinders of radius r whose axes cross at angle th, hosted on the first
    # (x = r cos u, y = r sin u, z = v): F = a v^2 + b v + c has discriminant
    # (2 r sin(th) cos(u))^2, a perfect square: it only touches zero, where the two
    # ellipses of the curve cross (meet.rs flags such an event a multiple root).
    u, v, r, th = sp.symbols("u v r theta", real=True)
    p = sp.Matrix([r * sp.cos(u), r * sp.sin(u), v])
    ax = sp.Matrix([sp.sin(th), 0, sp.cos(th)])
    q = sp.expand(p.dot(p) - (p.dot(ax)) ** 2 - r**2)
    a, b, c = [q.coeff(v, k) for k in (2, 1, 0)]
    d = sp.factor(sp.trigsimp(sp.expand(b**2 - 4 * a * c)))
    assert sp.simplify(d - (2 * r * sp.sin(th) * sp.cos(u)) ** 2) == 0, d
    # A sphere of radius R about the origin on a cylinder of radius r about the line
    # x = e: discriminant 4 (R^2 - r^2 - e^2 - 2 e r cos u); it touches zero (a double
    # root, the surfaces tangent at a point) exactly when R = r + |e|.
    R, e = sp.symbols("R e", real=True)
    p = sp.Matrix([e + r * sp.cos(u), r * sp.sin(u), v])
    q = sp.expand(p.dot(p) - R**2)
    a, b, c = [q.coeff(v, k) for k in (2, 1, 0)]
    d = sp.simplify(sp.expand(b**2 - 4 * a * c))
    assert sp.simplify(d - 4 * (R**2 - r**2 - e**2 - 2 * e * r * sp.cos(u))) == 0, d


def main():
    checks()
    d, c = quartic_disc()
    tw, tsyms = trig2_to_w()
    tl, lsyms = torus_on_line()
    lines = [
        "// Generated by tools/sympy/meet.py; do not edit.",
        "",
        "/// Discriminant of c0 + c1 s + c2 s^2 + c3 s^3 + c4 s^4.",
        "#[rustfmt::skip]",
        "pub fn quartic_disc(c: &[f64; 5]) -> f64 {",
        "    let [c0, c1, c2, c3, c4] = *c;",
        f"    {rust(d, c)}",
        "}",
        "",
        "/// (1 + w^2)^2 (a0 + a1 cos t + b1 sin t + a2 cos 2t + b2 sin 2t) with w = tan(t/2),",
        "/// ascending in w.",
        "#[rustfmt::skip]",
        "pub fn trig2_quartic(a0: f64, a1: f64, b1: f64, a2: f64, b2: f64) -> [f64; 5] {",
        "    [",
    ]
    lines += [f"        {rust(tw[k], tsyms)}," for k in range(5)]
    lines += [
        "    ]",
        "}",
        "",
        "/// The torus (|q|^2 + R^2 - r^2)^2 - 4 R^2 (qx^2 + qy^2) along q = p + v d (in the",
        "/// torus's frame), ascending in v.",
        "#[rustfmt::skip]",
        "pub fn torus_line(p: [f64; 3], d: [f64; 3], big: f64, r: f64) -> [f64; 5] {",
        "    let ([px, py, pz], [dx, dy, dz]) = (p, d);",
        "    let a0 = px * px + py * py + pz * pz + (big * big - r * r);",
        "    let a1 = 2.0 * (px * dx + py * dy + pz * dz);",
        "    let a2 = dx * dx + dy * dy + dz * dz;",
        "    let b0 = px * px + py * py;",
        "    let b1 = 2.0 * (px * dx + py * dy);",
        "    let b2 = dx * dx + dy * dy;",
        "    let rr = 4.0 * big * big;",
        "    [",
    ]
    lines += [f"        {rust(tl[k], lsyms)}," for k in range(5)]
    lines += ["    ]", "}"]
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
