//! Shared by the kernel regression tests written as Forge parts: build a part's text, and hold
//! it to what the kernel must do (valid, the same in sequence and in n-ary booleans).
#![allow(dead_code)]

use forge_lang::build::Cache;
use forge_lang::{Measure, Options, Run};

/// The part built, a scratch folder beside it holding the bench font (`text(..)` parts read it).
pub fn run(src: &str) -> (Run, Cache) {
    let dir = std::env::temp_dir().join(format!("forge-lang-tests-{}", std::process::id()));
    std::fs::create_dir_all(&dir).expect("temp dir");
    let font = dir.join(forge_agent::bench::FONT);
    if !font.exists() {
        std::fs::write(&font, forge_agent::bench::font_bytes()).expect("font");
    }
    let opts = Options {
        dir: Some(dir),
        ..Options::default()
    };
    forge_lang::run(src, opts, Cache::default())
}

/// Builds without error to a valid part; its measure.
pub fn holds(src: &str) -> Measure {
    let (r, _) = run(src);
    assert!(r.errors.is_empty(), "{}", forge_lang::report::text(&r, src));
    let m = r.measure.clone().expect("measured");
    assert_eq!(
        m.problems,
        0,
        "invalid: {:?}",
        &m.invalid[..m.invalid.len().min(3)]
    );
    m
}

/// The kernel's features this run sent, regenerated by the kernel alone: in sequence, and in
/// n-ary booleans on one thread. Each a list of solids' bodies, or the kernel's error.
pub fn regens(
    src: &str,
) -> (
    Result<Vec<forge_topo::Body>, String>,
    Result<Vec<forge_topo::Body>, String>,
) {
    let (r, cache) = run(src);
    assert!(r.errors.is_empty(), "{}", forge_lang::report::text(&r, src));
    let (f, ids) = cache.history();
    let part = forge_model::Part { features: f.to_vec() };
    let bodies = |x: Result<Vec<forge_model::Solid>, forge_model::RegenError>| {
        x.map(|s| s.into_iter().map(|s| s.body).collect())
            .map_err(|e| format!("{e:?}"))
    };
    (
        bodies(part.regenerate_solids_ids(Some(ids))),
        bodies(part.regenerate_nary_solids_ids(1, Some(ids))),
    )
}

/// `holds`, and the n-ary regen is valid too.
pub fn holds_nary(src: &str) -> Measure {
    let m = holds(src);
    let (_, nary) = regens(src);
    for b in nary.unwrap_or_else(|e| panic!("nary: {e}")) {
        let p = forge_topo::check::check(&b);
        assert!(p.is_empty(), "nary invalid: {:?}", &p[..p.len().min(3)]);
    }
    m
}

/// `holds_nary`, and sequence and n-ary give the same faces by name.
pub fn holds_alike(src: &str) -> Measure {
    let m = holds_nary(src);
    let names = |bs: Vec<forge_topo::Body>| {
        let mut n: Vec<_> = bs
            .iter()
            .flat_map(|b| b.face_ids().map(|f| b.face(f).name).collect::<Vec<_>>())
            .collect();
        n.sort();
        n
    };
    let (seq, nary) = regens(src);
    assert_eq!(seq.map(names), nary.map(names));
    m
}

/// Refused: the run's first error, as text.
pub fn refused(src: &str) -> String {
    let (r, _) = run(src);
    assert!(!r.errors.is_empty(), "built, expected a refusal");
    forge_lang::report::text(&r, src)
}
