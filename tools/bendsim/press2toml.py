#!/usr/bin/env python3
"""research/bendsim/env/data/press-brakes.md -> kernel/forge-brake/data/presses/presses.toml.
Every value cited. Rules (stated in the cites): the standard variant (first value of "a / b");
in -> mm x 25.4, ft x 304.8; force: kN, metric t x 9.80665, US ton x 8.896443 (a tonnage printed
as "Ton" is taken as metric: an estimate); a range "lo-hi" holds lo; backgauge ranges are kept as
record facts (no maker publishes the minimum stop, so the backgauge check reports not checked)."""
import re, sys

TAKEN = "2026-11-24"

def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'

def parse(path):
    recs, cur = [], None
    for line in open(path, encoding="utf-8"):
        if line.startswith("[[press]]"):
            cur = {}
            recs.append(cur)
            continue
        if cur is None:
            continue
        m = re.match(r"^([a-z_]+) = (\"[^\"]*\"|[^#]*?)\s*(?:#\s*(.*))?$", line.rstrip("\n"))
        if not m:
            if line.startswith("```") or line.startswith("#"):
                cur = None
            continue
        k, v, c = m.group(1), m.group(2).strip().strip('"'), (m.group(3) or "")
        parts = [p.strip() for p in c.split("|")]
        cur[k] = (v, parts[0] if parts else "", parts[1] if len(parts) > 1 else "", " | ".join(parts[2:]))
    return recs

def mm(v):
    if v is None or "UNKNOWN" in v or v.startswith("none") or v.strip() in ("-", ""):
        return None
    m = re.search(r"\(([0-9.]+)\s*mm", v)
    if m:
        return float(m.group(1)), True
    m = re.match(r"\s*([0-9]+(?:\.[0-9]+)?)", v)
    if not m:
        return None
    x = float(m.group(1))
    if re.match(r"\s*[0-9.]+\s*ft", v):
        return x * 304.8, True
    if re.match(r"\s*[0-9.]+\s*in", v):
        return x * 25.4, True
    return x, False

def force(v):
    if v is None or "UNKNOWN" in v:
        return None
    m = re.match(r"\s*([0-9]+(?:\.[0-9]+)?)\s*(kN|US ton|t\b|Ton)", v)
    if not m:
        return None
    x, u = float(m.group(1)), m.group(2)
    if u == "kN":
        return x, None
    if u == "US ton":
        return x * 8.896443, "US tons x 8.896443 kN"
    if u == "Ton":
        return x * 9.80665, "printed 'Ton': metric tonnes assumed (x 9.80665 kN)"
    return x * 9.80665, "metric t x 9.80665 kN"

def cite(path, e, status=None, basis=None, value=None):
    v, st, src, stmt = e
    w = (st.split()[0] if st else "").strip("(;,").lower()
    status = status or {"published": "published", "estimate": "estimate", "conflict": "conflict"}.get(w, "estimate")
    out = ["[[press.cite]]", f"path = {q(path)}", f"status = {q(status)}"]
    if src.startswith("http"):
        out += [f"source = {q(src)}", f"taken = {q(TAKEN)}"]
    elif status in ("published", "conflict"):
        status = "estimate"
        out[2] = 'status = "estimate"'
    out.append(f"value = {q(value or (v + (' -- ' + stmt if stmt else '')))}")
    if status in ("estimate", "unknown"):
        out.append(f"basis = {q(basis or st or 'as the notes state')}")
    if status == "conflict":
        out.append(f"note = {q(st)}")
    return "\n".join(out)

def main():
    recs = parse(sys.argv[1])
    out = ["# Press brakes: forgecad's records restated from the makers' openly published specs",
           "# (research/bendsim/env/data/press-brakes.md), every value cited. GENERATED by",
           "# tools/bendsim/press2toml.py. Bodies beyond these values (beams, fingers) are the",
           "# library's conservative stand-ins (catalog.rs). Verify against your machine.", ""]
    n = 0
    for r in recs:
        if "id" not in r:
            continue
        n += 1
        lines = ["[[press]]", f"id = {q(r['id'][0])}", f"maker = {q(r.get('maker', ('',))[0])}",
                 f"model = {q(r.get('model', ('',))[0])}", "real = true"]
        cites = []
        def num(dst, src, conv=mm, **kw):
            e = r.get(src)
            if not e:
                return
            x = conv(e[0])
            if x is None:
                return
            val, note = x
            lines.append(f"{dst} = {round(val, 2):g}")
            if note and conv is force:
                cites.append(cite(dst, e, value=f"{e[0]} -- {e[3]} ({note})", status="estimate" if "assumed" in note else None, basis=note))
            elif "/" in e[0] or "-" in e[0].split()[0]:
                cites.append(cite(dst, e, value=f"{e[0]} -- {e[3]} (the standard variant, first value)"))
            else:
                cites.append(cite(dst, e))
        num("force", "tonnage", force)
        num("bed_length", "bending_length")
        num("housing_gap", "housing_gap")
        num("open_height", "open_height")
        num("stroke", "stroke")
        num("throat", "throat")
        num("table_height", "table_height")
        for dst, src in (("speeds.approach", "speed_approach"), ("speeds.work", "speed_working"), ("speeds.return", "speed_return")):
            e = r.get(src)
            if e and (m := re.search(r"([0-9]+(?:\.[0-9]+)?)\s*mm/s", e[0])):
                lines.append(f"{dst} = {float(m.group(1)):g}".replace("speeds.", "speeds_"))
                cites.append(cite(dst, e))
        for src in ("backgauge_axes", "bg_x_range", "bg_x_travel", "bg_r_range", "bg_z_range", "bg_fingers", "clamping", "drive", "control", "overall_lwh", "weight"):
            e = r.get(src)
            if e and "UNKNOWN" not in e[0]:
                cites.append(cite("record", e, value=f"{src}: {e[0]} -- {e[3]}"))
        # speeds as a table
        sp = [l for l in lines if l.startswith("speeds_")]
        lines = [l for l in lines if not l.startswith("speeds_")]
        if sp:
            lines.append("speeds = { " + ", ".join(l.replace("speeds_", "") for l in sp) + " }")
        out.append("\n".join(lines) + "\n\n" + "\n\n".join(cites) + "\n")
    open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out))
    print(sys.argv[2], n)

main()
