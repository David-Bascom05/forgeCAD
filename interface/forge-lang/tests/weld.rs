#[test]
fn three_members_at_a_node() {
    // the rule at a node of three: the first two in order meet by the corner (a miter), the
    // third is butted to each of them: the leg stops on their underside, 20 below the node
    let src = format!("{CORNER3}f = members([lay.a, lay.b, up.leg], section: \"SHS 40x40x3\")\n");
    let m = common::holds_alike(&src);
    assert_eq!(m.bodies, 3);
    let rs = rows(&src);
    near(row(&rs, "f[0]").cut.overall.unwrap(), 520.0, 1e-9, "rail a");
    near(row(&rs, "f[1]").cut.overall.unwrap(), 420.0, 1e-9, "rail b");
    let leg = row(&rs, "f[2]");
    near(leg.cut.length, 280.0, 1e-9, "leg");
    near(leg.cut.overall.unwrap(), 280.0, 1e-9, "leg");
    assert_eq!(
        leg.cut.ends[0].len(),
        2,
        "the leg's top is cut by both rails' planes"
    );
    let b = solids(&src);
    near(extent(&b[2], 2), 280.0, 1e-6, "leg body");
    // members never overlap: the bodies' volumes add up to the part's
    let sum: f64 = b.iter().map(|x| forge_topo::mass::mass(x).unwrap().volume).sum();
    near(sum, m.volume, 1e-6, "disjoint");
    // ranked first, the leg runs on and the rails are butted to it
    let src = format!(
        "{CORNER3}f = members([lay.a, lay.b, up.leg], section: \"SHS 40x40x3\", corner: \"butt\", rank: [2])\n"
    );
    common::holds_alike(&src);
    let rs = rows(&src);
    near(
        row(&rs, "f[2]").cut.overall.unwrap(),
        300.0 + 20.0,
        1e-9,
        "leg runs on",
    );
}

#[test]
fn arc_members_tangent_and_mitered() {
    // a line, a tangent arc, a line: the joints are in line, so square
    let src = "shared R = 150
sketch lay(on: xy) {
  path p(start: (0, 0)) {
    line(to: (300, 0))
    tarc(to: (300 + R, R))
    line(to: (300 + R, 400))
  }
}
bend = members(lay.p, section: \"CHS 48.3x3.2\")
";
    let m = common::holds_alike(src);
    let a = PI * (24.15f64.powi(2) - 20.95f64.powi(2));
    near(m.volume, a * (300.0 + 150.0 * PI / 2.0 + 250.0), 1e-6, "Pappus");
    let rs = rows(src);
    let arc = row(&rs, "bend[1]");
    let (r, turn) = arc.cut.arc.expect("an arc row");
    near(r, 150.0, 1e-9, "radius");
    near(turn, 90.0, 1e-9, "turn");
    near(arc.cut.length, 150.0 * PI / 2.0, 1e-9, "arc length");
    assert!(arc.cut.ends.iter().flatten().all(|e| e.angle < 1e-9));
    // an arc meeting a line at an angle: both cut on the bisecting plane
    let src = "sketch lay(on: xy) {
  c = pt(0, 0)
  s = pt(200, 0)
  e = pt(0, 200)
  a = arc(center: c, from: s, to: e)
  l = line(e, (-200, 300))
}
ring = members([lay.a, lay.l], section: \"SHS 30x30x3\")
";
    let m = common::holds_alike(src);
    assert_eq!(m.bodies, 2);
}

#[test]
fn sections_placed_and_custom() {
    // an angle on its centroid: the miters pass through the centroid, so the volume is A times
    // the path's length again; mirrored and turned it is the same
    for extra in [
        "",
        ", mirror: true",
        ", turn: 90deg",
        ", mirror: true, turn: 180deg",
    ] {
        let src = format!("{RECT}top = members(lay.r, section: \"L 50x50x5\", align: \"centroid\"{extra})\n");
        let m = common::holds(&src);
        let a = forge_weld::lookup("L 50x50x5").unwrap().area();
        near(m.volume, a * 2000.0, 1e-6, extra);
    }
    // a section drawn in a sketch: a 30 x 10 bar, its origin on the path
    let src = format!(
        "{RECT}sketch sec(on: xy) {{\n  b = rect(center: (0, 0), size: (30, 10))\n}}\ntop = members(lay.r, section: sec.b)\n"
    );
    let m = common::holds(&src);
    near(m.volume, 300.0 * 2000.0, 1e-6, "sketched");
    // offset, and the library's IPE and UPE
    for s in [
        "\"IPE 200\", align: \"bottom\"",
        "\"UPE 100\", offset: (5, 5)",
        "\"FB 40x5\"",
    ] {
        let src = format!("{RECT}top = members(lay.r, section: {s})\n");
        common::holds(&src);
    }
}

#[test]
fn end_trim_to_a_plane_and_a_cope() {
    // a post trimmed to a work plane 200 up: its cut list length follows
    let src = format!(
        "{CORNER3}post = members(up.leg, section: \"SHS 40x40x3\")\ncap_at = workplane(offset: lay, d: 200)\nt = end_trim(post[0], to: cap_at)\n"
    );
    let m = common::holds(&src);
    near(m.volume, shs40x3() * 200.0, 1e-6, "trimmed");
    let rs = rows(&src);
    near(row(&rs, "post[0]").cut.length, 200.0, 1e-9, "length");
    // round tube coped to a round rail: one piece, valid, shorter than uncut
    let src = "sketch lay(on: xy) {
  r = line((0, 0), (600, 0))
  base = line((0, 0), (600, 0), construction: true)
}
sketch up(on: rotate(lay.plane, about: lay.base, by: 90deg)) {
  l = line((300, 0), (300, 400))
}
rail = members(lay.r, section: \"CHS 60.3x4\")
leg = members(up.l, section: \"CHS 48.3x3.2\")
cope = end_trim(leg[0], to: rail[0])
";
    let m = common::holds(src);
    assert_eq!(m.bodies, 2);
    let b = solids(src);
    let legv = forge_topo::mass::mass(&b[1]).unwrap().volume;
    let a = PI * (24.15f64.powi(2) - 20.95f64.powi(2));
    assert!(legv < a * 400.0 && legv > a * (400.0 - 30.15), "coped: {legv}");
    let rs = rows(src);
    assert_eq!(row(&rs, "leg[0]").copes[0], ["rail[0]"]);
}

#[test]
fn caps_and_corner_plates() {
    let src = format!(
        "{RECT}top = members(lay.r, section: \"SHS 40x40x3\", corner: \"butt\")\ng = corner_plate(top[0], top[1], size: 80, t: 5, chamfer: 10)\n"
    );
    let m = common::holds(&src);
    assert_eq!(m.bodies, 5);
    // the plate's corner sits where the inside faces meet; its outline is the triangle of legs
    // 80 less the chamfer's corner of legs 10
    let b = solids(&src);
    let pv = forge_topo::mass::mass(&b[4]).unwrap().volume;
    near(pv, (80.0 * 80.0 / 2.0 - 10.0 * 10.0 / 2.0) * 5.0, 1e-6, "plate");
    let src = "sketch lay(on: xy) {
  l = line((0, 0), (500, 0))
}
bar = members(lay.l, section: \"RHS 60x40x3\")
cap = end_cap(bar[0], end: \"end\", t: 4)
cap0 = end_cap(bar[0], end: \"start\", t: 4)
";
    let m = common::holds(src);
    assert_eq!(m.bodies, 3);
    let b = solids(src);
    let outline = forge_weld::lookup("RHS 60x40x3").unwrap().outline().area();
    near(
        forge_topo::mass::mass(&b[1]).unwrap().volume,
        outline * 4.0,
        1e-6,
        "cap",
    );
    near(extent(&b[1], 0), 4.0, 1e-9, "cap thickness");
    // the caps sit outside the ends
    let bx = forge_lang::tightbox::tight_box(&b[2]);
    near(bx.x.lo, -4.0, 1e-9, "start cap");
}

#[test]
fn members_take_ordinary_features() {
    let src = format!(
        "{RECT}top = members(lay.r, section: \"SHS 40x40x3\")\nround = fillet(edges(of: top[0], crease: \"convex\"), 1)\nsketch hs(on: top[2].start) {{\n  c = circle((0, 0), 4)\n}}\n"
    );
    common::holds(&src);
    let src = format!(
        "{RECT}top = members(lay.r, section: \"SHS 40x40x3\")\nall = union(top[0], tools: [top[1], top[2], top[3]])\n"
    );
    let m = common::holds(&src);
    assert_eq!(m.bodies, 1);
    near(m.volume, shs40x3() * 2000.0, 1e-6, "welded");
}

#[test]
fn refusals() {
    let src = format!("{RECT}top = members(lay.r, section: \"SHS 41x3\")\n");
    let t = common::refused(&src);
    assert!(t.contains("UnknownSize") && t.contains("SHS 40x40x3"), "{t}");
    let (r, _) = common::run(&src);
    assert!(!r.errors[0].fixes().is_empty(), "nearest sizes offered");
    let src = "sketch lay(on: xy) {
  o = poly([(0, 0), (300, 0), (300, 200)], closed: false)
}
arm = members(lay.o, section: \"SHS 40x40x3\")
cap = end_cap(arm[0], end: \"end\", t: 4)
";
    assert!(common::refused(src).contains("CapOnSlantEnd"));
    let src = "sketch lay(on: xy) {
  a = line((0, 0), (300, 0))
  b = line((0, 0), (300, 0.0000001))
}
f = members([lay.a, lay.b], section: \"SHS 40x40x3\")
";
    let t = common::refused(src);
    // folding back on itself: no miter plane crosses either member
    assert!(t.contains("MiterTooSharp") || t.contains("CutAlongMember"), "{t}");
}

