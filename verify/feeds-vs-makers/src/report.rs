//! The readable report: summaries by material group, tool type, op class and maker, the outlier
//! clusters (ratio under 0.5 or over 1.5), the material classing and what was skipped.
use crate::{CLASSES, Row, Skips, generic_held_out, stats, summary};

fn fmt(s: Option<(f64, f64, f64, usize)>) -> String {
    match s {
        Some((m, lo, hi, n)) => format!("{m:.2} ({lo:.2}–{hi:.2}, n {n})"),
        None => "–".into(),
    }
}

fn table<F: Fn(&Row) -> String>(rows: &[Row], title: &str, key: F) -> String {
    let mut s = format!(
        "\n### By {title}\n\n| {title} | rpm ours/theirs | fz ours/theirs | feed rate ours/theirs |\n|---|---|---|---|\n"
    );
    for (k, a, b, c) in summary(rows, key) {
        s.push_str(&format!("| {k} | {} | {} | {} |\n", fmt(a), fmt(b), fmt(c)));
    }
    s
}

pub fn markdown(rows: &[Row], skips: &Skips) -> String {
    let mill: Vec<Row> = rows.iter().filter(|r| r.kind != "drill").cloned().collect();
    let drill: Vec<Row> = rows.iter().filter(|r| r.kind == "drill").cloned().collect();
    let mut s = String::from("# Our feeds and speeds against the tool makers' published numbers\n\n");
    s.push_str("Generated by `cargo run -p feeds-vs-makers` (verify/feeds-vs-makers). Ratios are ours / theirs; each cell is the median (10th–90th percentile, count). Ours (presets OFF): forge_tooling::resolve with the maker's own preset off, i.e. the generic default (the 10th percentile of the tool's class, below), at the maker's own ae/ap, no machine clamps; presets ON is its own section. Theirs: CAM-HAAS's cited raw rows (research/cam/tooling/raw/*.json; each row's URL is in rows.tsv). Ranges are taken at their middle.\n\n");
    s.push_str(&summary_for_david(&mill, &drill));
    s.push_str(&generic_section(rows));
    s.push_str(&presets_on(rows));
    s.push_str(&format!(
        "\n## Milling ({} rows)\n\nAll: rpm {}, fz {}, feed rate {}.\n",
        mill.len(),
        fmt(stats(mill.iter().map(|r| r.r_rpm()).collect())),
        fmt(stats(mill.iter().filter_map(|r| r.r_f()).collect())),
        fmt(stats(mill.iter().filter_map(|r| r.r_vf()).collect()))
    ));
    s.push_str(&table(&mill, "group", |r| r.group.to_string()));
    s.push_str(&table(&mill, "substrate", |r| r.substrate.to_string()));
    s.push_str(&table(&mill, "tool type", |r| r.kind.clone()));
    s.push_str(&table(&mill, "op class", |r| r.op.clone()));
    s.push_str(&table(&mill, "maker", |r| r.vendor.clone()));
    s.push_str(&table(&mill, "group × op class", |r| {
        format!("{} {}", r.group, r.op)
    }));
    s.push_str(&format!(
        "\n## Drilling ({} rows; `circular` rows are the very tables our defaults hold)\n",
        drill.len()
    ));
    s.push_str(&table(&drill, "group × substrate × independent", |r| {
        format!(
            "{} {} {}",
            r.group,
            r.substrate,
            if r.circular { "circular" } else { "independent" }
        )
    }));
    s.push_str(&table(&drill, "maker", |r| r.vendor.clone()));
    // outlier clusters
    s.push_str("\n## Outliers (a ratio under 0.5 or over 1.5), clustered by maker, group, op, tool type\n\n| cluster | rows | rpm median | fz median |\n|---|---|---|---|\n");
    let out: Vec<&Row> = rows
        .iter()
        .filter(|r| {
            let o = |x: f64| !(0.5..=1.5).contains(&x);
            o(r.r_rpm()) || r.r_f().is_some_and(o)
        })
        .collect();
    let mut keys: Vec<String> = out
        .iter()
        .map(|r| format!("{} {} {} {}", r.vendor, r.group, r.op, r.kind))
        .collect();
    keys.sort();
    keys.dedup();
    for k in keys {
        let sel: Vec<&&Row> = out
            .iter()
            .filter(|r| format!("{} {} {} {}", r.vendor, r.group, r.op, r.kind) == k)
            .collect();
        s.push_str(&format!(
            "| {k} | {} | {} | {} |\n",
            sel.len(),
            fmt(stats(sel.iter().map(|r| r.r_rpm()).collect())),
            fmt(stats(sel.iter().filter_map(|r| r.r_f()).collect()))
        ));
    }
    s.push_str("\n## How the makers' material texts were classed (first match wins)\n\n| keywords | ISO 513 group |\n|---|---|\n");
    for (k, g) in CLASSES {
        s.push_str(&format!(
            "| {} | {} |\n",
            k.join(", "),
            if g.is_empty() { "not compared" } else { g }
        ));
    }
    s.push_str("\n## Skipped\n\n");
    for (why, n) in &skips.0 {
        s.push_str(&format!("- {why}: {n}\n"));
    }
    s
}

/// The short readable summary.
fn summary_for_david(mill: &[Row], drill: &[Row]) -> String {
    let med = |v: Vec<f64>| stats(v).map_or(f64::NAN, |x| x.0);
    let by = |g: &str, f: &dyn Fn(&Row) -> Option<f64>| {
        med(mill.iter().filter(|r| r.group == g).filter_map(f).collect())
    };
    let all: Vec<Row> = [mill, drill].concat();
    let ho = generic_held_out(&all);
    let maker = |m: &str| {
        let sel: Vec<_> = ho.iter().filter(|x| all[x.0].vendor == m).collect();
        let v: Vec<f64> = sel.iter().map(|x| x.1).collect();
        let c: Vec<f64> = sel.iter().filter_map(|x| x.2).collect();
        let pct =
            |v: &[f64]| 100.0 * v.iter().filter(|x| **x > 1.0 + 1e-9).count() as f64 / v.len().max(1) as f64;
        (med(v.clone()), pct(&v), med(c.clone()), pct(&c))
    };
    let (lv, lvp, lc, lcp) = maker("lakeshore");
    let mut s = String::from("## Summary\n\n");
    s.push_str("- \"Are we the worst of all worlds by averaging manufacturer specs?\" For a tool with no maker data the default was one pooled median per material group. It is now the **10th percentile (P10) of the tool's class** (material group × op class × maker tier × flutes × coating × helix, opened up where a class has under 10 rows or one maker), with the class's min/P10/P25/median/max shown next to the value so it can be pushed up knowingly. A tool with maker presets uses them first (next section but one).\n");
    s.push_str(&format!(
        "- The independent check (each maker against classes built from the others only): Lakeshore, the general-purpose maker and the closest stand-in for an unknown tool, gets {lv:.2}× its own speed and {lc:.2}× its own chip at the median; our default is above its own number in {lvp:.0}% of its rows (speed) and {lcp:.0}% (chip) (target: about 5% or less).\n"
    ));
    s.push_str("- What the data cannot split: each helix angle is one maker's product line, the general-purpose tier is one maker (Lakeshore), and H is one maker (Helical), so those classes never reach two makers and the lookup opens them up; the classes that exist are the material-specific makers' (Harvey, Helical) by op, flutes and coating in M, N and P.\n");
    s.push_str(&format!(
        "- Over {} cited end-mill rows, our generic default runs {:.2}× the makers' spindle speed and {:.2}× their feed per tooth at the median (in-sample: the classes are built from these rows, so under 1 is by construction).\n",
        mill.len(),
        med(mill.iter().map(|r| r.r_rpm()).collect()),
        med(mill.iter().filter_map(|r| r.r_f()).collect())
    ));
    s.push_str("- Per material group (median speed / chip, ours/theirs): ");
    let gs: Vec<String> = ["P", "M", "K", "N", "S", "H"]
        .iter()
        .map(|g| {
            format!(
                "{g} {:.2} / {:.2}",
                by(g, &|r| Some(r.r_rpm())),
                by(g, &|r| r.r_f())
            )
        })
        .collect();
    s.push_str(&gs.join(", "));
    s.push_str(". H stays on the group table (one maker).\n");
    let ind: Vec<&Row> = drill.iter().filter(|r| !r.circular).collect();
    s.push_str(&format!(
        "- Drills are unchanged by this (their own sourced model): {} rows; all but {} are rows our drill defaults were set from, so they check drift, not independence.\n",
        drill.len(),
        ind.len()
    ));
    s.push_str("- Model checks against makers' own published adjustments: radial chip thinning matches Helical's and Harvey's formula (forge-tooling feeds tests); ball-nose effective diameter matches CNCCookbook's worked example; a maker's preset reproduces its own row inside the printed range for every row (Presets ON).\n");
    s
}

fn on_table<F: Fn(&Row) -> String>(rows: &[&Row], title: &str, key: F) -> String {
    let mut s = format!("\n| {title} | rows | rpm ours/theirs | f ours/theirs |\n|---|---|---|---|\n");
    let mut keys: Vec<String> = rows.iter().map(|r| key(r)).collect();
    keys.sort();
    keys.dedup();
    for k in keys {
        let sel: Vec<&&Row> = rows.iter().filter(|r| key(r) == k).collect();
        s.push_str(&format!(
            "| {k} | {} | {} | {} |\n",
            sel.len(),
            fmt(stats(sel.iter().filter_map(|r| r.on_rpm()).collect())),
            fmt(stats(sel.iter().filter_map(|r| r.on_f()).collect()))
        ));
    }
    s
}

/// Presets ON: what an op actually gets by default when its tool carries the maker's presets.
fn presets_on(rows: &[Row]) -> String {
    let on: Vec<&Row> = rows.iter().filter(|r| r.on.is_some()).collect();
    let own: Vec<&Row> = rows.iter().filter(|r| r.own.is_some()).collect();
    let exact = own.iter().filter(|r| r.own_in_range() == Some(true)).count();
    let mut s = String::from("\n## Presets ON (the real default path)\n\n");
    s.push_str(&format!(
        "Each row run again as an op of the language runs it: the tool's own maker preset taken by `Tool::preset_for` for the op's class (the representative \"<group> <class>\", i.e. the maker's row for the group's representative material; a maker's slot row runs as a slot, rough as a pocket, max as a clearing, finish as a contour, which `Tool::class_for` classes finish at a finishing width; the rest general), at the maker's ae/ap, no machine clamps. {} of {} rows have a preset for their group on their tool (the rest fall back to the generic table above).\n\n",
        on.len(),
        rows.len()
    ));
    s.push_str(&format!(
        "- All: rpm {}, f {}.\n",
        fmt(stats(on.iter().filter_map(|r| r.on_rpm()).collect())),
        fmt(stats(on.iter().filter_map(|r| r.on_f()).collect()))
    ));
    s.push_str(&format!(
        "- Reproduction: run with the preset written for that very row (its material text and engagement), {exact} of {} rows give a speed and feed inside the maker's printed range (ratio to the range's middle: rpm {}, f {}; the presets take a printed range at its low end, the maker's \"start here\", where this report takes the middle). This checks the inch conversion and that a preset's feed is read as the maker's programmed feed at its own width.\n",
        own.len(),
        fmt(stats(own.iter().filter_map(|r| r.own_rpm()).collect())),
        fmt(stats(own.iter().filter_map(|r| r.own_f()).collect()))
    ));
    s.push_str("- What the spread below means: this pass names no stock material, so the representative preset stands for every material of its group on that tool (e.g. Harvey's wrought-aluminium row for a cast copper part), and rows of other materials differ by the maker's own material-to-material spread. When the part names its material (forge-material), `Tool::preset_for_material` takes the maker's row for it instead (alloy named in the maker's text, else its family pattern; the slowest hardness class among equals): tests `presets_by_stock_material_and_class` and `a_makers_tool_takes_its_row_for_the_stock_material`.\n");
    s.push_str(&on_table(&on, "group", |r| r.group.to_string()));
    s.push_str(&on_table(&on, "maker", |r| r.vendor.clone()));
    s.push_str(&on_table(&on, "maker op class", |r| r.op.clone()));
    s.push_str(&on_table(&on, "representative material?", |r| {
        let p = &r.on.as_ref().unwrap().preset;
        if r.own.is_some() && r.own_rpm() == r.on_rpm() && r.own_f() == r.on_f() {
            format!("same numbers as the row's own ({p})")
        } else {
            "another material or class".into()
        }
    }));
    s
}

/// The generic path: classes, P10, and the hold-out of P10-by-class against each maker.
fn generic_section(rows: &[Row]) -> String {
    let lib = forge_tooling::Library::builtin();
    let mut s = String::from("\n## The generic default: 10th percentile by tool class\n\n");
    s.push_str(&format!(
        "A tool with no maker preset takes its speed and chip from its **class**: material group × op class × maker tier × flute count × coating × helix band (kernel/forge-tooling/data/generic.toml, {} classes, generated from these rows: `cargo run -p feeds-vs-makers -- --generic`). A class is written only with at least {} rows from at least {} makers; where the tool's own class has fewer, the lookup opens dimensions in this order: helix, tier, coating, flute count, op class (the class used is named in the value's note). The default is the class's **10th percentile (P10)**, not its median (coordinator's decision, after P25 was still above the general-purpose maker's own number in ~1 row in 5): a speed or chip that is too high breaks tools, one too low only costs time, and the default applies only to tools with no maker data. The resolved value carries the class's min / P10 / P25 / median / max (`Resolved::spread`), so the user can push up knowingly.\n\n",
        lib.generics.len(),
        crate::GENERIC_MIN_ROWS,
        crate::GENERIC_MIN_MAKERS
    ));
    s.push_str("What the makers' data supports: helix is one product line's in this data (Lakeshore 30°, Helical 35°/45°, Harvey 37°/42°), so no helix class has two makers; the general-purpose tier is Lakeshore's alone, so no general-purpose class has two makers either; H has one maker (Helical) and stays on the group table; K and S resolve at group level (any op). The classes that exist are the material-specific makers' (Harvey, Helical) by op, flutes and coating in M, N, P.\n\n");
    let ho = generic_held_out(rows);
    s.push_str("### Held out: each maker against P10-by-class built from the other makers only\n\n| maker | rows scored | P10 speed / maker's (median, 10–90%) | rows where P10 speed is above the maker's | P10 chip / maker's | rows where P10 chip is above the maker's |\n|---|---|---|---|---|---|\n");
    let mut makers: Vec<&str> = ho.iter().map(|x| rows[x.0].vendor.as_str()).collect();
    makers.sort();
    makers.dedup();
    for m in makers {
        let sel: Vec<_> = ho.iter().filter(|x| rows[x.0].vendor == m).collect();
        let above = |v: Vec<f64>| {
            let n = v.len();
            let a = v.iter().filter(|x| **x > 1.0 + 1e-9).count();
            if n == 0 {
                "–".to_string()
            } else {
                format!("{a} of {n} ({:.0}%)", 100.0 * a as f64 / n as f64)
            }
        };
        let vs: Vec<f64> = sel.iter().map(|x| x.1).collect();
        let cs: Vec<f64> = sel.iter().filter_map(|x| x.2).collect();
        s.push_str(&format!(
            "| {m} | {} | {} | {} | {} | {} |\n",
            sel.len(),
            fmt(stats(vs.clone())),
            above(vs),
            fmt(stats(cs.clone())),
            above(cs)
        ));
    }
    s.push_str("\nA maker's rows scored against the others' classes: under 1 means our default is under that maker's own number. Lakeshore (the only general-purpose maker) is the case that matters for an unknown tool: it is scored against classes made from the material-specific makers only.\n");
    s
}
