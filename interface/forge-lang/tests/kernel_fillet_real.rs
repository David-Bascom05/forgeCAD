//! Fillets as real parts ask for them, each restated in its own numbers from a shape a dataset
//! part had, as a Forge part: every one valid on both regens and of exactly the volume and area
//! worked out here.
mod common;

use forge_math::dmath;
use forge_model::Part;
use forge_topo::Body;
use std::f64::consts::PI;

/// The part's history as the kernel takes it: its features and their ids.
fn history(src: &str) -> (Part, Vec<u64>) {
    let (r, cache) = common::run(src);
    assert!(r.errors.is_empty(), "{}", forge_lang::report::text(&r, src));
    let (f, ids) = cache.history();
    (Part { features: f.to_vec() }, ids.to_vec())
}

/// The part regenerated by the kernel alone, sequentially and in n-ary booleans on two threads.
fn regens(src: &str) -> [(&'static str, Result<Body, forge_model::RegenError>); 2] {
    let (part, ids) = history(src);
    let nary =
        part.regenerate_nary_solids_ids(2, Some(&ids)).and_then(
            |s| match <[forge_model::Solid; 1]>::try_from(s) {
                Ok([s]) => Ok(s.body),
                Err(s) => Err(forge_model::RegenError::Bodies { count: s.len() }),
            },
        );
    [("seq", part.regenerate_ids(Some(&ids))), ("n-ary", nary)]
}

/// The finished part, its build free of errors.
fn body(src: &str) -> Body {
    let (r, _) = common::run(src);
    assert!(r.errors.is_empty(), "{}", forge_lang::report::text(&r, src));
    r.body.expect("a part")
}

/// The feature the kernel refused, and how.
fn refusal(src: &str) -> (String, String) {
    let (r, _) = common::run(src);
    r.errors
        .iter()
        .find_map(|e| match e {
            forge_lang::error::Error::Build { id, error, .. } => Some((id.clone(), format!("{error:?}"))),
            _ => None,
        })
        .unwrap_or_else(|| panic!("no kernel refusal: {}", forge_lang::report::text(&r, src)))
}

fn exact(src: &str, volume: f64, area: f64) {
    for (how, built) in regens(src) {
        let b = built.unwrap_or_else(|e| panic!("{how}: {e:?}\n{src}"));
        let problems = forge_topo::check(&b);
        assert!(problems.is_empty(), "{how}: {problems:?}\n{src}");
        let p = forge_topo::mass::mass(&b).expect("mass");
        assert!(
            (p.volume - volume).abs() < 1e-5 * volume,
            "{how} volume {} not {volume}\n{src}",
            p.volume
        );
        assert!(
            (p.area - area).abs() < 1e-5 * area,
            "{how} area {} not {area}\n{src}",
            p.area
        );
    }
}

fn count(b: &Body, kind: impl Fn(&forge_geom::Surface) -> bool) -> usize {
    b.face_ids().filter(|&f| kind(&b.face(f).surface)).count()
}

fn procedural(s: &forge_geom::Surface) -> bool {
    matches!(s, forge_geom::Surface::Procedural(_))
}

/// A block `w` x `d` x `h` from the origin, its sketch `s` (rect `r`), its extrude `b`.
fn block(w: f64, d: f64, h: f64) -> String {
    format!(
        "sketch s(on: xy) {{\n  r = rect(corner: (0, 0), size: ({w:?}, {d:?}))\n}}\nb = extrude(s, {h:?})\n"
    )
}

/// A disc of radius `r`, `h` thick, on the origin: sketch `s` (circle `c`), extrude `b`.
fn disc(r: f64, h: f64) -> String {
    format!("sketch s(on: xy) {{\n  c = circle((0, 0), {r:?})\n}}\nb = extrude(s, {h:?})\n")
}

#[test]
fn two_rounds_beside_a_sharp_edge_mitre() {
    // two cylinders of radius r cut each other in a plane; each removes (1 - pi/4) r^2 of section
    // along its edge up to the mitre, and where they overlap the solid under both is integrated
    let (w, d, h, r) = (100.0f64, 80.0f64, 40.0f64, 5.0f64);
    // the removed volume of a corner of two rounds: along each edge (length - r) of section, and in
    // the last r square, the union of the two: (2 - pi/2) r^2 r - common, common = (1 - pi/4)^... by integration
    let n = 2000;
    let mut corner = 0.0;
    for i in 0..n {
        for j in 0..n {
            let (x, y) = ((i as f64 + 0.5) / n as f64 * r, (j as f64 + 0.5) / n as f64 * r);
            let drop = |t: f64| r - (r * r - t * t).max(0.0).sqrt();
            corner += drop(x).max(drop(y)) * (r / n as f64) * (r / n as f64);
        }
    }
    let side = (1.0 - PI / 4.0) * r * r;
    let volume = w * d * h - side * (w - r) - side * (d - r) - corner;
    let b = body(&format!(
        "{}round = fillet(edges(between: (b.end, b.side(s.r[2]))) + edges(between: (b.end, b.side(s.r[1]))), {r:?})\n",
        block(w, d, h)
    ));
    let p = forge_topo::mass::mass(&b).expect("mass");
    assert!((p.volume - volume).abs() < 1e-2, "{} not {volume}", p.volume);
    assert!(forge_topo::check(&b).is_empty());
    // and nothing beside the two cylinders: no patch
    assert_eq!(count(&b, procedural), 0);
}

